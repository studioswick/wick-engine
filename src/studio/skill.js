// SKILL.md for AI agents. The hand-written guide is the SKILL.md file shipped with the engine; the property reference
// at the end is generated from the same class schema the engine runs on, so it cannot drift from what scripts and
// tree files can actually do.

import { CLASS_DEFS, MATERIALS, SURFACES, GRAPHICS_FLOORS } from '../engine/datamodel.js';
import { WICK_SOUNDS, soundId, WICK_TEXTURES, textureId, VOID_TEXTURE, WICK_MESHES, meshId } from '../engine/library.js';
import { LIBRARY_SCRIPTS } from '../engine/libscripts.js';
import { WICK_BUNDLES } from '../engine/bundles.js';
import { WICK_VERSION } from '../version.js';

const TYPE = { number: 'number', boolean: 'boolean', string: 'string', source: 'string (Lua source)', enum: 'enum', vector3: 'Vector3  (x,y,z)', vector2: 'Vector2  (x,y)', udim2: 'UDim2  (xScale,xOffset,yScale,yOffset)', color: 'Color3  (#rrggbb or r,g,b in 0..1)' };

function fmt(def) {
  const d = def.default;
  if (def.type === 'enum') return `"${d}"`;
  if (def.type === 'string') return d === '' ? '""' : `"${d}"`;
  if (def.type === 'source') return '(script text)';
  return Array.isArray(d) ? d.join(',') : String(d);
}

function range(def) {
  if (def.type === 'enum') return def.options.join(' / ');
  if (def.type === 'number' && def.min !== undefined) return `${def.min} to ${def.max}`;
  if (def.when) return 'only shown for some values of other properties';
  return '';
}

/** Markdown tables for every class, straight from the schema. */
export function generateReference() {
  const out = [`## Appendix: property reference (generated by Wick Engine ${WICK_VERSION})`, ''];
  for (const [name, def] of Object.entries(CLASS_DEFS)) {
    if (name === 'DataModel') continue;
    const props = Object.entries(def.props).filter(([, d]) => !d.runtime || name === 'Part');
    out.push(`### ${name}`, def.service ? `Service (always exists, cannot be created or destroyed).` : `Create with \`Instance.new("${name}", parent)\` or a tree line \`${name} Name ...\`.`, '');
    out.push('| Property | Type | Default | Range / options |', '|---|---|---|---|', `| Name | string | "${name}" | |`);
    for (const [p, d] of props) out.push(`| ${p}${d.runtime ? ' (runtime only)' : ''} | ${TYPE[d.type]} | ${fmt(d)} | ${range(d)} |`);
    out.push('');
  }
  out.push('### Materials', '| Material | Friction x | Bounce x | Rolling resistance |', '|---|---|---|---|');
  for (const m of MATERIALS) out.push(`| ${m} | ${SURFACES[m].grip} | ${SURFACES[m].bounce} | ${SURFACES[m].roll} |`);
  out.push('', '### Built-in library ids',
    `- Sounds: ${WICK_SOUNDS.map((n) => `\`${soundId(n)}\``).join(', ')}`,
    `- Textures: ${WICK_TEXTURES.map((n) => `\`${textureId(n)}\``).join(', ')}, and \`${VOID_TEXTURE}\` (unlit; shows TextureColor exactly)`,
    `- Meshes: ${WICK_MESHES.map((n) => `\`${meshId(n)}\``).join(', ')}`,
    `- Scripts you can copy from \`src/library/scripts/\`: ${LIBRARY_SCRIPTS.map((s) => `\`${s.id}\``).join(', ')}`,
    `- Bundles: ${WICK_BUNDLES.map((b) => `\`${b.id}\``).join(', ')}`,
    `- Lighting.MinGraphics options: ${GRAPHICS_FLOORS.join(', ')}`, '');
  return out.join('\n');
}

/** The full SKILL.md text: the shipped guide plus the generated reference. */
export async function loadSkillText() {
  let guide = '# Wick Engine agent skill\n\n(SKILL.md could not be loaded. Check the file is deployed next to index.html.)\n';
  try {
    const res = await fetch('SKILL.md', { cache: 'no-cache' });
    if (res.ok) guide = await res.text();
  } catch { /* offline and not cached yet */ }
  return `${guide.trimEnd()}\n\n${generateReference()}`;
}

export function downloadText(name, text) {
  const url = URL.createObjectURL(new Blob([text], { type: 'text/markdown' }));
  const a = Object.assign(document.createElement('a'), { href: url, download: name });
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
